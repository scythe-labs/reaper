class TestUnknownDegradation:
    def _random_policy(self, rng: random.Random, media_type: str) -> PolicyBody:
        policy = default_policy(media_type)
        gates = []
        for g in policy.gates:
            entry = g.model_dump(mode="json")
            if g.gate is GateId.RATING_FLOOR:
                entry.update(threshold=rng.randint(1, 100), secondary=rng.randint(1, 10000))
            elif g.gate is GateId.MIN_DORMANCY:
                entry.update(threshold=rng.randint(365, 4000))
            elif g.gate is GateId.SERVER_POPULARITY:
                entry.update(threshold=rng.randint(1, 10), window_days=rng.randint(1, 2000))
            gates.append(entry)
        signals = [
            {**s.model_dump(mode="json"), "weight": rng.randint(0, 100)} for s in policy.signals
        ]
        signals = balanced(signals)
        return mutated(
            policy,
            gates=gates,
            signals=signals,
            condemn_at=rng.randint(1, 100),
            coverage_floor_bp=rng.choice((0, 2500, 5000, 8000)),
        )

    @pytest.mark.parametrize("media_type", ["movie", "season"])
    def test_degrading_any_fact_to_unknown_never_condemns_and_never_raises_a_score(
        self, media_type: str
    ) -> None:
        rng = random.Random(2)
        pool = (MOVIES if media_type == "movie" else SEASONS)[:70]
        policies = [default_policy(media_type)] + [
            self._random_policy(rng, media_type) for _ in range(5)
        ]
        for policy in policies:
            gates = build_gates(policy)
            for v in pool:
                verdict, score = judge(v, policy, gates)[:2]
                known = [n for n in DEGRADABLE if v["facts"][n]["state"] == "known"]
                probes = [[n] for n in known]
                if len(known) >= 3:
                    probes.append(rng.sample(known, 3))
                for names in probes:
                    after_verdict, after_score = judge(degraded(v, names), policy, gates)[:2]
                    assert after_score <= score, (
                        f"degrading {names} raised the score {score} -> {after_score}"
                    )
                    if verdict != "condemn":
                        assert after_verdict != "condemn", (
                            f"degrading {names} flipped {v['id']} {verdict} -> condemn"
                        )


