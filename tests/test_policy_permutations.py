def _mutant_body(rng: random.Random) -> dict:
    """A near-valid policy body: the shipped defaults with a few random mutations, some
    legal and some not. Mirrors what an operator's UI edits actually produce."""
    body = rng.choice((DEFAULT_MOVIE_POLICY, DEFAULT_TV_POLICY)).model_dump(mode="json")
    for _ in range(rng.randint(0, 3)):
        roll = rng.random()
        if roll < 0.2 and body["gates"]:
            gate = rng.choice(body["gates"])
            gate[rng.choice(("threshold", "secondary", "window_days"))] = rng.choice(
                (-3, 0, 1, 75, 365, 1095, 10**6)
            )
            gate["enabled"] = rng.random() > 0.25
        elif roll < 0.4 and body["signals"]:
            signal = rng.choice(body["signals"])
            signal[rng.choice(("weight", "saturate_at", "floor"))] = rng.choice(
                (-1, 0, 1, 50, 100, 101, 1825)
            )
        elif roll < 0.55:
            body["custom_condemn"] = [
                {
                    "kind": rng.choice(("boolean", "graded")),
                    "name": rng.choice(("a", "unwatched", "x" * 61, "")),
                    "field": rng.choice([*BY_KEY, "bogus_field"]),
                    "op": rng.choice([o.value for o in Op]),
                    "value": rng.choice((True, False, 0, 365, "Genre01", "500", "A, B")),
                    "weight": rng.choice((0, 30, 100, 101, -1)),
                    "saturate_at": rng.choice((1, 100, 0)),
                    "floor": rng.choice((0, 50, 100)),
                }
            ]
        elif roll < 0.7:
            body["protect_conditions"] = [
                {
                    "field": rng.choice([*BY_KEY, "bogus_field"]),
                    "op": rng.choice([o.value for o in Op]),
                    "value": rng.choice((True, 5, "Genre01", "500", 10**13)),
                }
            ]
        elif roll < 0.85:
            body["graded_keeps"] = [
                {
                    "name": "keep",
                    "field": rng.choice([*BY_KEY, "bogus_field"]),
                    "max_discount": rng.choice((1, 40, 100, 0, 101)),
                    "floor": rng.choice((0, 10)),
                    "saturate_at": rng.choice((1, 20, 0)),
                    "direction": rng.choice(("high_keeps", "low_keeps", "bogus")),
                }
            ]
        else:
            body[rng.choice(("condemn_at", "coverage_floor_bp", "keep_last_seasons"))] = rng.choice(
                (-5, 0, 1, 50, 100, 101, 10000, 10001)
            )
    return body


class TestValidationRuntimeContract:
    def test_anything_that_validates_scores_and_inspects_without_an_exception(
        self,
    ) -> None:
        rng = random.Random(3)
        probe = MOVIES[:15] + SEASONS[:15]
        accepted = 0
        for _ in range(150):
            body = _mutant_body(rng)
            try:
                policy = PolicyBody.model_validate(body)
            except ValueError:
                continue
            accepted += 1
            gates = build_gates(policy)
            for v in probe:
                verdict, score, coverage_bp, _, _ = judge(v, policy, gates)
                assert verdict in ("protect", "abstain", "condemn")
                assert 0 <= score <= 100
                assert 0 <= coverage_bp <= 10000
            inspect(policy, ProfileSettings())
        assert accepted >= 20, "the mutation generator stopped producing valid policies"


