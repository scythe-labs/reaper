class TestDecideVerdictMatrix:
    def test_the_decision_matches_its_spec_at_every_boundary(self) -> None:
        for protected in (False, True):
            for blocked in (False, True):
                for safety in (False, True):
                    for override in (None, "reap"):
                        for score, condemn_at in ((69, 70), (70, 70), (0, 1), (100, 100)):
                            for coverage_bp, floor_bp in (
                                (4999, 5000),
                                (5000, 5000),
                                (0, 0),
                                (10000, 0),
                            ):
                                got = decide_verdict(
                                    protected=protected,
                                    blocked=blocked,
                                    safety_protected=safety,
                                    score=score,
                                    coverage_bp=coverage_bp,
                                    condemn_at=condemn_at,
                                    coverage_floor_bp=floor_bp,
                                    override=override,
                                )
                                if override == "reap":
                                    expect = "protect" if (blocked or safety) else "condemn"
                                elif protected:
                                    expect = "protect"
                                elif blocked or coverage_bp < floor_bp:
                                    expect = "abstain"
                                elif score >= condemn_at:
                                    expect = "condemn"
                                else:
                                    expect = "abstain"
                                assert got == expect


