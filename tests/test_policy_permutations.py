"""The policy permutation lab: every user-tunable option, exercised over real shapes.

The policy engine exposes a large option surface -- gates with thresholds and windows,
weighted signals, user-authored condemn rules, protect conditions, graded keeps, two
decision thresholds, and eight season-pruning toggles. Any combination is a legal
operator configuration, and a bug in an untested combination deletes files. This module
sweeps that space against ``tests/fixtures/policy_lab_vectors.json``: a de-identified
sample of real library shapes (observation states, day counts, watcher counts) with a
pinned baseline, generated by ``scripts/policy_lab_extract.py``.

Every check here is an *invariant*, not an example: a property that must hold across the
whole permutation space, in the direction that keeps files. The three load-bearing ones:

* **Missing data never condemns.** Degrading any fact to Unknown may never flip an item
  into the condemned set, and may never raise its score.
* **Protections only ever narrow the condemned set.** Adding a gate, a protect
  condition, or a keep can never condemn something the same policy without it spared.
* **Anything that validates must score.** A policy the save boundary accepts must run
  through gates, scorer, and verdict without an exception, on every real shape.

The pinned baseline turns the fixture into an engine-drift trip-wire: any change to
scoring or verdict semantics shows up as a baseline diff, which an intentional change
acknowledges by regenerating the fixture.
"""

