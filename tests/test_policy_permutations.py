@st.composite
def legal_policies(draw: st.DrawFn) -> PolicyBody:
    media_type = draw(st.sampled_from(("movie", "tv")))
    base = DEFAULT_MOVIE_POLICY if media_type == "movie" else DEFAULT_TV_POLICY
    gates = []
    for g in base.gates:
        entry = g.model_dump(mode="json")
        entry["enabled"] = draw(st.booleans())
        if g.gate is GateId.RATING_FLOOR:
            entry["threshold"] = draw(st.integers(1, 100))
            entry["secondary"] = draw(st.integers(1, 3_000_000))
        elif g.gate is GateId.MIN_DORMANCY:
            entry["threshold"] = draw(st.integers(365, 10_000))
        elif g.gate is GateId.SERVER_POPULARITY:
            entry["threshold"] = draw(st.integers(1, 50))
        entry["window_days"] = draw(st.integers(1, 5000))
        gates.append(entry)
    signals = []
    for s in base.signals:
        saturate = draw(st.integers(1, 5000))
        signals.append(
            {
                "signal": s.signal.value,
                "weight": draw(st.integers(0, 100)),
                "saturate_at": saturate,
                "floor": draw(st.integers(0, saturate - 1)),
            }
        )
    signals = balanced(signals)
    return PolicyBody.model_validate(
        {
            **base.model_dump(mode="json"),
            "gates": gates,
            "signals": signals,
            "condemn_at": draw(st.integers(1, 100)),
            "coverage_floor_bp": draw(st.integers(0, 10_000)),
            "keep_last_seasons": draw(st.integers(0, 12)),
            "season_lookahead": draw(st.integers(0, 4)),
            "in_progress_hold_days": draw(st.integers(0, 1000)),
        }
    )


class TestPolicySpaceProperties:
    @settings(max_examples=80, deadline=None)
    @given(policy=legal_policies(), index=st.integers(0, len(VECTORS) - 1))
    def test_any_legal_policy_scores_any_real_shape_in_bounds(
        self, policy: PolicyBody, index: int
    ) -> None:
        vector = VECTORS[index]
        verdict, score, coverage_bp, evaluation, _ = judge(vector, policy)
        assert verdict in ("protect", "abstain", "condemn")
        assert 0 <= score <= 100
        assert 0 <= coverage_bp <= 10000
        if evaluation.protected and not vector.get("override"):
            assert verdict == "protect"

    @settings(max_examples=40, deadline=None)
    @given(policy=legal_policies(), index=st.integers(0, len(VECTORS) - 1))
    def test_full_degradation_never_condemns_under_any_legal_policy(
        self, policy: PolicyBody, index: int
    ) -> None:
        """The blackout case: every observable fact Unknown at once. Whatever the
        policy, the engine may keep or abstain; it may never condemn."""
        vector = VECTORS[index]
        if vector.get("override") == "reap":  # a hand-reap is the owner's own decision
            return
        blackout = degraded(vector, list(DEGRADABLE))
        verdict, score, _, _, _ = judge(blackout, policy)
        assert verdict != "condemn"
        assert score == 0
