class TestPinnedBaseline:
    def test_every_vector_reproduces_its_baseline_under_the_default_policies(self) -> None:
        """If this fails, the engine's behaviour changed for real library shapes.

        That may be intentional -- a scorer change bumps SCORER_VERSION -- in which case
        regenerate the fixture (scripts/policy_lab_extract.py) in the same change, so the
        diff records exactly what moved. If you did not mean to change scoring, this is
        the bug.
        """
        mismatches = []
        for v in VECTORS:
            verdict, score, coverage_bp, _, _ = judge(
                v, default_policy(v["media_type"]), default_gates(v["media_type"])
            )
            base = v["baseline"]
            if (verdict, score, coverage_bp) != (
                base["verdict"],
                base["score"],
                base["coverage_bp"],
            ):
                mismatches.append(
                    f"{v['id']}: baseline {base} -> ({verdict}, {score}, {coverage_bp})"
                )
        assert not mismatches, "\n".join(mismatches[:10])


class TestFixtureStaysDeidentified:
    def test_no_identifying_fields_survive_regeneration(self) -> None:
        """The fixture is committed; the golden rule applies to it as to code. Guard the
        regeneration script against ever re-leaking titles, keys, paths, or hosts."""
        raw = FIXTURE.read_text()
        data = json.loads(raw)
        forbidden = {"title", "media_key", "group_key", "rating_key", "host", "path", "user"}

        def walk(obj) -> None:
            if isinstance(obj, dict):
                for key, value in obj.items():
                    assert key not in forbidden, f"identifying key {key!r} in fixture"
                    walk(value)
            elif isinstance(obj, list):
                for value in obj:
                    walk(value)

        walk(data)
        for v in data["vectors"]:
            genres = v["facts"]["genres"]
            if genres["state"] == "known":
                for token in genres["value"].split(", "):
                    assert token.startswith("Genre"), f"raw genre name {token!r} in fixture"


