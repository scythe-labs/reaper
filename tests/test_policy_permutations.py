class TestThresholdMonotonicity:
    @pytest.mark.parametrize("media_type", ["movie", "season"])
    def test_raising_either_threshold_never_grows_the_condemned_set(self, media_type: str) -> None:
        pool = MOVIES if media_type == "movie" else SEASONS
        policy = default_policy(media_type)
        judged = [(v, judge(v, policy, default_gates(media_type))) for v in pool]
        grid = {}
        for condemn_at in (1, 30, 69, 70, 71, 100):
            for floor_bp in (0, 2500, 5000, 10000):
                condemned = set()
                for v, (_, score, coverage_bp, evaluation, _) in judged:
                    verdict = decide_verdict(
                        protected=evaluation.protected,
                        blocked=evaluation.blocked,
                        safety_protected=False,
                        score=score,
                        coverage_bp=coverage_bp,
                        condemn_at=condemn_at,
                        coverage_floor_bp=floor_bp,
                        override=v.get("override"),
                    )
                    if verdict == "condemn":
                        condemned.add(v["id"])
                grid[(condemn_at, floor_bp)] = condemned
        for floor_bp in (0, 2500, 5000, 10000):
            for low, high in itertools.pairwise((1, 30, 69, 70, 71, 100)):
                assert grid[(high, floor_bp)] <= grid[(low, floor_bp)]
        for condemn_at in (1, 30, 69, 70, 71, 100):
            for low, high in itertools.pairwise((0, 2500, 5000, 10000)):
                assert grid[(condemn_at, high)] <= grid[(condemn_at, low)]


class TestGateToggles:
    @pytest.mark.parametrize("media_type", ["movie", "season"])
    def test_dropping_any_gate_only_moves_verdicts_toward_condemn(self, media_type: str) -> None:
        """Removing a protection may condemn more, never less -- and never un-condemn."""
        pool = (MOVIES if media_type == "movie" else SEASONS)[:120]
        policy = default_policy(media_type)
        baseline = {v["id"]: judge(v, policy, default_gates(media_type))[0] for v in pool}
        for dropped in [g.gate for g in policy.gates]:
            without = mutated(
                policy,
                gates=[g.model_dump(mode="json") for g in policy.gates if g.gate is not dropped],
            )
            gates = build_gates(without)
            for v in pool:
                after = judge(v, without, gates)[0]
                assert VERDICT_RANK[after] >= VERDICT_RANK[baseline[v["id"]]], (
                    f"dropping {dropped.value} moved {v['id']} toward protection"
                )

    @pytest.mark.parametrize("media_type", ["movie", "season"])
    def test_random_gate_subsets_hold_the_same_direction(self, media_type: str) -> None:
        rng = random.Random(1)
        pool = (MOVIES if media_type == "movie" else SEASONS)[:80]
        policy = default_policy(media_type)
        baseline = {v["id"]: judge(v, policy, default_gates(media_type))[0] for v in pool}
        for _ in range(8):
            subset = [g for g in policy.gates if rng.random() > 0.4]
            smaller = mutated(policy, gates=[g.model_dump(mode="json") for g in subset])
            gates = build_gates(smaller)
            for v in pool:
                after = judge(v, smaller, gates)[0]
                assert VERDICT_RANK[after] >= VERDICT_RANK[baseline[v["id"]]]


class TestGateThresholds:
    def test_a_higher_rating_floor_never_protects_more(self) -> None:
        # The rating floor now lives in keep_rating_rules (one IMDb bar), so raise the bar
        # there and confirm the protected set only ever shrinks.
        protected_at: dict[int, set[str]] = {}
        for floor in (1, 50, 75, 90, 100):
            policy = mutated(
                DEFAULT_MOVIE_POLICY,
                keep_rating_rules=[{"source": "imdb", "floor": floor, "min_votes": 1000}],
            )
            gates = build_gates(policy)
            protected_at[floor] = {
                v["id"] for v in MOVIES if judge(v, policy, gates)[0] == "protect"
            }
        for low, high in itertools.pairwise((1, 50, 75, 90, 100)):
            assert protected_at[high] <= protected_at[low]

    def test_a_longer_dormancy_floor_never_protects_less(self) -> None:
        protected_at: dict[int, set[str]] = {}
        for threshold in (365, 730, 1095, 3650):
            policy = mutated(
                DEFAULT_MOVIE_POLICY,
                gates=[
                    {**g.model_dump(mode="json"), "threshold": threshold}
                    if g.gate is GateId.MIN_DORMANCY
                    else g.model_dump(mode="json")
                    for g in DEFAULT_MOVIE_POLICY.gates
                ],
            )
            gates = build_gates(policy)
            protected_at[threshold] = {
                v["id"] for v in MOVIES if judge(v, policy, gates)[0] == "protect"
            }
        for low, high in itertools.pairwise((365, 730, 1095, 3650)):
            assert protected_at[low] <= protected_at[high]

    def test_a_wider_popularity_window_never_protects_less(self) -> None:
        """Watchers are recomputed per window from the fixture's real play recency, the
        way a real scan would gather them -- not merely re-thresholded."""
        protected_at: dict[int, set[str]] = {}
        for window in (7, 90, 365, 1825):
            policy = mutated(
                DEFAULT_MOVIE_POLICY,
                gates=[
                    {**g.model_dump(mode="json"), "window_days": window}
                    if g.gate is GateId.SERVER_POPULARITY
                    else g.model_dump(mode="json")
                    for g in DEFAULT_MOVIE_POLICY.gates
                ],
            )
            gates = build_gates(policy)
            protected_at[window] = {
                v["id"]
                for v in MOVIES
                if judge(with_watchers_window(v, window), policy, gates)[0] == "protect"
            }
        for low, high in itertools.pairwise((7, 90, 365, 1825)):
            assert protected_at[low] <= protected_at[high]


