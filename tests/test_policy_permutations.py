class TestPolicyHash:
    def test_every_semantic_field_changes_the_hash_and_only_thresholds_spare_scoring(
        self,
    ) -> None:
        policy = DEFAULT_MOVIE_POLICY
        base_hash, base_scoring = policy.policy_hash(), policy.scoring_hash()
        post_score_fields = {"condemn_at", "coverage_floor_bp"}
        flips: dict[str, object] = {
            "condemn_at": policy.condemn_at % 100 + 1,
            "coverage_floor_bp": (policy.coverage_floor_bp + 1) % 10_000,
            "keep_last_seasons": policy.keep_last_seasons + 1,
            "keep_first_season": not policy.keep_first_season,
            "keep_last_scope": "requested",
            "season_lookahead": policy.season_lookahead + 1,
            "keep_in_progress": not policy.keep_in_progress,
            "in_progress_hold_days": policy.in_progress_hold_days + 1,
            "keep_specials": not policy.keep_specials,
            "flag_keep_conflicts": not policy.flag_keep_conflicts,
            "keep_tags": ["another-tag"],
            "keep_tags_match": "all",
            # A reallocation, not a bump: the total is pinned at 100, so the only weight
            # edit an operator can make is moving points between signals.
            "signals": balanced(
                [
                    {**s.model_dump(mode="json"), "weight": (s.weight + 7) % 101 or 1}
                    for s in policy.signals
                ]
            ),
        }
        for field_name, value in flips.items():
            changed = mutated(policy, **{field_name: value})
            assert changed.policy_hash() != base_hash, f"{field_name} not hashed"
            scoring_changed = changed.scoring_hash() != base_scoring
            assert scoring_changed == (field_name not in post_score_fields), (
                f"{field_name}: scoring hash coverage is wrong"
            )

    def test_the_hash_ignores_nothing_it_should_cover_on_a_round_trip(self) -> None:
        policy = DEFAULT_TV_POLICY
        again = PolicyBody.model_validate_json(policy.canonical_json())
        assert again.policy_hash() == policy.policy_hash()


