"""The scoring surface, pinned to the ``SCORER_VERSION`` it was cut against.

An approved run is bound to its snapshot's ``policy_hash`` and the executor refuses to send
when the live hash no longer matches (rule 113). That hash digests the *policy body*, so an
upgrade the body cannot express is invisible to it: add a ``Facts`` field, a signal, or a
protection, and every stored body hashes exactly as before. Nothing marks the snapshot as
predating the build, and the plan already sitting on the Reap page executes on evidence the
old code gathered, uncovered by whatever the new code added.

The mechanism that closes that already exists and works. ``scorer_version`` is a
``PolicyBody`` field, ``policy_hash`` digests it with the rest of the body, and
``_pin_to_the_running_scorer`` rewrites a stored body's value to the running constant on
load, so bumping ``SCORER_VERSION`` moves every policy's hash and voids every pending
approval. What did not exist was anything making the author bump it. It was discipline, on
the change most likely to forget: the one that adds evidence rather than editing a threshold.

So this file records the surface, and the version it was recorded at, and fails when the two
disagree. Recorded as a literal list rather than a digest because the record is read by a
reviewer as much as by the suite: an added field shows up in the diff as one line beside a
``SCORER_VERSION`` that did or did not move, where a hex string shows a hex string.

**What a failure asks for is a decision, and bumping is not the only right answer.** The
worked example is the commit this file was written against. #492 added ``Facts.on_lists`` and
took ``whitelisted`` and ``curated_list`` out of the policy vocabulary, all with
``SCORER_VERSION`` sitting still -- which is this file's failure exactly. It was still
correct, because it invalidated through the body instead: both gates were rows in the shipped
default, so every stored body names them, ``convert_list_protections`` rewrites each one into
the equivalent ``on_list`` keep rule on load, and that edit moves ``policy_hash`` for every
install on its own. An operator whose decisions could change had their approval voided; one
whose body did not move had nothing reading the new fact. So the surface moved and the
meaning did not, and re-recording without a bump was right. What the gate buys is that
somebody had to work that out and write it down, rather than the question never being asked.

**What it does not catch.** Arithmetic. A ramp that changes shape, a weight table rebalanced,
a threshold that means something new -- the surface holds still through all of it and this
file stays green. Declarations are what a walk can see. ``test_policy_permutations``'s
``TestPinnedBaseline`` is the guard for that half: it replays de-identified fact shapes
through the shipped defaults and goes red when a verdict, score or coverage moves. It *asks*
for the bump in its failure text rather than enforcing one, because the fixture it compares
against is regenerated by the same change -- so between the two, a declaration that moves is
enforced and arithmetic that moves is announced.
"""

from __future__ import annotations

import dataclasses

from reaper.engine.gates import POLICY_AUTHORABLE_GATES, Facts, GateId
from reaper.engine.policy import SCORER_VERSION
from reaper.engine.signals import SignalId

#: The ``SCORER_VERSION`` the surface below was recorded against. Both move together or
#: neither does -- re-recording the list without touching this leaves every operator's
#: pending approval bound to a scorer that no longer exists.
