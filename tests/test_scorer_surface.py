_BUMP = (
    "The scoring surface moved, so decide what invalidates the plans approved under the old "
    "one. A scan under this code gathers or judges something the old one did not, and a "
    "stored policy body hashes the same either side of that -- so an approved run would "
    "execute on evidence gathered without it (rule 113). Two answers are legitimate and you "
    "have to pick one in writing. Either bump SCORER_VERSION in engine/policy.py, which "
    "moves every policy's hash and asks every operator to re-scan; or show that a loader "
    "shim already rewrites every affected stored body, which moves those hashes on its own "
    "(convert_list_protections is the worked example, see this file's docstring). Then set "
    "_RECORDED_AT_SCORER_VERSION to the running SCORER_VERSION and re-record the list above."
)


def _gate_role(gate: GateId) -> str:
    """Whether a policy body may still carry this gate, read off the one shipped declaration.

    Deliberately two answers and not four. A gate that stops being authorable leaves the
    operator's vocabulary, and *that* is what belongs on a surface record. Which mechanism
    took it -- retired outright, converted into a keep rule by a shim, emitted by the engine
    with no policy row -- is a question ``test_policy`` already owns and pins, and the only
    declaration in ``src`` that answers it is this set. An earlier draft guessed the rest and
    labeled the two gates #492 converted "engine-emitted", which was simply untrue.
    """
    return "authorable" if gate in POLICY_AUTHORABLE_GATES else "not-authorable"


def _scoring_surface(facts_cls: type = Facts) -> tuple[str, ...]:
    """Every evidence field, signal, and protection the running code declares.

    Derived from the declarations themselves rather than transcribed beside them, so the only
    hand-maintained copy is the recorded one this is compared against -- which is the copy a
    reviewer reads.

    A ``Facts`` field carries its annotation, not just its name: retyping one changes what the
    scan gathers as surely as adding one does (rules 140 and 142 are both that shape). The
    annotations are strings here because ``engine.gates`` imports ``annotations`` from
    ``__future__``, so this compares the declaration as written; a purely cosmetic re-spelling
    would fire it, and re-recording with no bump is the right answer to that one.

    ``facts_cls`` is a parameter so a test can hand it a stand-in for some future commit's
    ``Facts`` -- ``facts_codec._observation_fields`` takes one for the same reason.
    """
    lines = [f"facts.{field.name}: {field.type}" for field in dataclasses.fields(facts_cls)]
    lines += [f"signal.{signal.value}" for signal in SignalId]
    lines += [f"gate.{gate.value}: {_gate_role(gate)}" for gate in GateId]
    return tuple(sorted(lines))


class TestTheSurfaceAndTheScorerVersionMoveTogether:
    def test_the_recorded_surface_is_the_one_the_code_declares(self) -> None:
        """The gate. It fails on the commit that adds the field, not on the server that
        deletes under it."""
        assert _scoring_surface() == _RECORDED_SURFACE, _BUMP

    def test_the_record_names_the_running_scorer(self) -> None:
        """The other half. Re-recording the surface while leaving this behind would swallow
        the failure above and leave every pending approval bound to the superseded scorer,
        which is the bug this file exists for."""
        assert _RECORDED_AT_SCORER_VERSION == SCORER_VERSION, _BUMP


class TestTheWalkSeesWhatItClaimsTo:
    """Rule 118: a matching record proves nothing about a walk that stopped collecting, so
    the two assumptions the record was cut under get their own tests."""

    def test_a_facts_field_this_commit_has_never_seen_reaches_the_surface(self) -> None:
        """Rule 145: the walk is proven against a member it did not collect, not only against
        the ones already in the record. A stand-in stands for the commit that adds the field,
        which is the commit this whole file is for."""
        added = "surface_walk_probe"
        assert added not in {f.name for f in dataclasses.fields(Facts)}, (
            f"{added} is a real field now; the stand-in needs a name Facts does not carry, or "
            "make_dataclass raises on the duplicate and this reads as a walk that broke"
        )
        future_facts = dataclasses.make_dataclass(
            "Facts",
            [
                *(
                    (f.name, f.type, dataclasses.field(default=None))
                    for f in dataclasses.fields(Facts)
                ),
                (added, "Observation[int]", dataclasses.field(default=None)),
            ],
            frozen=True,
        )

        surface = _scoring_surface(future_facts)

        assert f"facts.{added}: Observation[int]" in surface
        assert surface != _RECORDED_SURFACE

    def test_a_facts_annotation_is_the_string_the_record_was_cut_from(self) -> None:
        """``field.type`` is source text under ``from __future__ import annotations`` and the
        type object without it. The surface renders either through an f-string, so dropping
        that import from ``engine.gates`` would silently re-spell all twenty lines as
        ``reaper.engine.observation.Observation[int]`` and the gate would fire for a reason
        nobody could read off the failure."""
        annotation = {f.name: f.type for f in dataclasses.fields(Facts)}["size_bytes"]

        assert isinstance(annotation, str)
        assert annotation == "Observation[int]"
